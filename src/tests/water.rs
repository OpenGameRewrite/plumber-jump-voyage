pub(super) fn run() {
    only_an_entry_finds_the_surface();
    an_ignored_start_area_shoots_back_from_the_end();
    an_ignored_end_area_finds_nothing();
    cylinder_arrows_keep_the_executable_cap_and_side_rules();
    cylinder_arrows_use_the_area_frame_and_scaled_normal();
    cylinder_executable_cases();
}

/// [V] AreaShapeCylinder 0x807458 -> checkHitSegmentCylinder 0x92cc5c.
#[cfg_attr(test, test)]
fn cylinder_arrows_keep_the_executable_cap_and_side_rules() {
    assert_eq!(
        cylinder_arrow(Vec3::new(0., 600., 0.), Vec3::ZERO, 0.),
        Some((Vec3::new(0., 500., 0.), Vec3::Y))
    );
    assert_eq!(
        cylinder_arrow(Vec3::new(0., 10., 0.), Vec3::new(1000., 10., 0.), 0.),
        Some((Vec3::new(500., 10., 0.), Vec3::new(500., 0., 0.)))
    );
    assert!(cylinder_arrow(Vec3::new(0., 10., 0.), Vec3::new(0., 20., 0.), 0.).is_none());
    // The original lateral solution is a ray, with no cap-height or segment-length clip.
    assert_eq!(
        cylinder_arrow(Vec3::new(1000., 1000., 0.), Vec3::new(900., 1000., 0.), 0.),
        Some((Vec3::new(500., 1000., 0.), Vec3::new(500., 0., 0.)))
    );
    // Cap rim and side tangency are excluded by the original strict tests.
    assert!(cylinder_arrow(Vec3::new(500., 600., 0.), Vec3::new(500., 0., 0.), 0.).is_none());
    assert!(
        cylinder_arrow(
            Vec3::new(500., 10., -1000.),
            Vec3::new(500., 10., 1000.),
            0.
        )
        .is_none()
    );
}

#[cfg_attr(test, test)]
fn cylinder_arrows_use_the_area_frame_and_scaled_normal() {
    for shape in [
        Shape::CylinderBase,
        Shape::CylinderCenter,
        Shape::CylinderTop,
    ] {
        let area = Area {
            shape,
            matrix: [0., -1., 0., 30., 1., 0., 0., 50., 0., 0., 1., 70.],
            scale: Vec3::new(2., 3., 4.),
            priority: 0,
            ignore: false,
        };
        let (bottom, top) = shape.span();
        let from = area.world_pos(Vec3::new(0., top + 100., 0.));
        let to = area.world_pos(Vec3::new(0., bottom, 0.));
        assert_eq!(
            area.arrow(from, to),
            Some((area.world_pos(Vec3::new(0., top, 0.)), Vec3::NEG_X))
        );
        let y = bottom + 10.;
        let from = area.world_pos(Vec3::new(1000., y, 0.));
        let to = area.world_pos(Vec3::new(0., y, 0.));
        assert_eq!(
            area.arrow(from, to),
            Some((area.world_pos(Vec3::new(500., y, 0.)), Vec3::Y))
        );
    }
}

/// Optional local oracle generated by executing 0x92cc5c, never copied from traces.
#[cfg_attr(test, test)]
fn cylinder_executable_cases() {
    let Ok(path) = std::env::var("PJV_CYLINDER_CASES") else {
        return;
    };
    let cases: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
    for case in cases.as_array().unwrap() {
        let v = |key: &str| {
            Vec3::from_array(std::array::from_fn(|i| {
                case[key][i].as_f64().unwrap() as f32
            }))
        };
        let hit = cylinder_arrow(v("a"), v("b"), case["bottom"].as_f64().unwrap() as f32);
        assert_eq!(hit.is_some(), case["hit"].as_bool().unwrap(), "{case}");
        if let Some((point, normal)) = hit {
            assert_eq!(
                point.to_array().map(f32::to_bits),
                v("point").to_array().map(f32::to_bits),
                "point {case}"
            );
            assert_eq!(
                normal.to_array().map(f32::to_bits),
                v("normal").to_array().map(f32::to_bits),
                "normal {case}"
            );
        }
    }
}

/// A pool (surface at 100, 1000 deep) and a one-sided ignored area stacked over it (100..300).
fn pool_with_ignored_cap() -> WaterAreas {
    let mut areas = WaterAreas::demo_box(0., 0., 500., 500., 100., 1000.);
    let mut cap = WaterAreas::demo_box(0., 0., 500., 500., 300., 200.).areas;
    cap[0].ignore = true;
    areas.areas.extend(cap);
    areas
}

/// 0x545008 needs `isInWaterPos(start)` false and `isInWaterPos(start + offset)` true: from above
/// into the pool finds the top face, the same arrow leaving the pool finds nothing.
#[cfg_attr(test, test)]
fn only_an_entry_finds_the_surface() {
    let pool = WaterAreas::demo_box(0., 0., 500., 500., 100., 1000.);
    let above = Vec3::new(0., 150., 0.);
    let down = Vec3::new(0., -100., 0.);
    let (position, normal) = pool.surface_by_arrow(above, down).expect("an entry");
    assert_eq!((position.y, normal), (100., Vec3::Y));
    assert!(pool.surface_by_arrow(above + down, -down).is_none());
    // Both ends in the water, or both out of it.
    assert!(pool.surface_by_arrow(Vec3::new(0., 0., 0.), down).is_none());
    assert!(
        pool.surface_by_arrow(above, Vec3::new(0., 10., 0.))
            .is_none()
    );
}

/// The start inside an ignored area (no water) with the end in the pool below it: the arrow
/// runs from the end back up to the start against the ignored area, whose floor normal (down)
/// comes out reversed (up).
#[cfg_attr(test, test)]
fn an_ignored_start_area_shoots_back_from_the_end() {
    let areas = pool_with_ignored_cap();
    let start = Vec3::new(0., 200., 0.);
    let (position, normal) = areas
        .surface_by_arrow(start, Vec3::new(0., -150., 0.))
        .expect("an entry through the ignored area's floor");
    assert_eq!((position.y, normal), (100., Vec3::Y));
}

/// An end inside an ignored area is no water: nothing is found.
#[cfg_attr(test, test)]
fn an_ignored_end_area_finds_nothing() {
    let areas = pool_with_ignored_cap();
    let start = Vec3::new(0., 400., 0.);
    assert!(
        areas
            .surface_by_arrow(start, Vec3::new(0., -200., 0.))
            .is_none()
    );
}
